#!/bin/sh
set -eu
psql --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" --set=ON_ERROR_STOP=1 \
  --set=app_password="$APP_DB_PASSWORD" --set=migration_password="$MIGRATOR_DB_PASSWORD" <<'SQL'
CREATE ROLE inrole_migrator LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS PASSWORD :'migration_password';
CREATE ROLE inrole_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS PASSWORD :'app_password';
ALTER DATABASE inrole OWNER TO inrole_migrator;
REVOKE ALL ON DATABASE inrole FROM PUBLIC;
GRANT CONNECT ON DATABASE inrole TO inrole_app;
REVOKE ALL ON SCHEMA public FROM PUBLIC;
SQL
